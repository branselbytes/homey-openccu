// in the adjacent modules from physical proportions and functional features.
// No OpenCCU/OCCU image files are copied, traced or converted. Manufacturer
// references in each module are for form only, not wiring/installation advice.
// Run: node scripts/generate-device-artwork.mjs
// sharp is supplied by the Homey CLI development dependency; it is not packaged.
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { format } from "prettier";
import { electricalDrivers } from "./device-artwork-electrical.mjs";
import {
  householdDrivers,
  householdModels,
} from "./device-artwork-household.mjs";
import { sensorDrivers } from "./device-artwork-sensors.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const drivers = { ...electricalDrivers, ...householdDrivers, ...sensorDrivers };

function document(name, geometry) {
  return (
    `<!-- ${name}: original OpenCCU for Homey illustration; MIT licensed. Generated by scripts/generate-device-artwork.mjs. -->\n` +
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 960 960"><g fill="none" stroke="#000" stroke-width="14" stroke-linecap="round" stroke-linejoin="round">${geometry}</g></svg>\n`
  );
}

async function writeSvg(filename, name, geometry) {
  const normalized = await fitToCanvas(name, geometry);
  const svg = await format(document(name, normalized), { parser: "html" });
  await writeFile(filename, svg);
  return svg;
}

async function fitToCanvas(name, geometry) {
  // Measure our own rendered strokes to give every product the same margin.
  // This is canvas layout, not extraction or tracing of third-party images.
  const { data, info } = await sharp(Buffer.from(document(name, geometry)))
    .resize(960, 960)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let left = info.width;
  let top = info.height;
  let right = -1;
  let bottom = -1;
  for (let y = 0; y < info.height; y += 1) {
    for (let x = 0; x < info.width; x += 1) {
      if (data[(y * info.width + x) * info.channels + 3] === 0) continue;
      left = Math.min(left, x);
      top = Math.min(top, y);
      right = Math.max(right, x);
      bottom = Math.max(bottom, y);
    }
  }
  if (right < left) throw new Error(`Empty device artwork: ${name}`);
  const scale = 864 / Math.max(right - left + 1, bottom - top + 1);
  const x = 480 - ((left + right + 1) / 2) * scale;
  const y = 480 - ((top + bottom + 1) / 2) * scale;
  return `<g transform="translate(${x.toFixed(6)} ${y.toFixed(6)}) scale(${scale.toFixed(6)})">${geometry}</g>`;
}

async function writeCatalogImages(directory, svg) {
  await mkdir(resolve(directory, "images"), { recursive: true });
  for (const [size, pixels] of [
    ["small", 75],
    ["large", 500],
  ]) {
    await sharp(Buffer.from(svg))
      .resize(pixels, pixels)
      .flatten({ background: "#fff" })
      .png()
      .toFile(resolve(directory, "images", `${size}.png`));
  }
}

for (const [name, geometry] of Object.entries(drivers)) {
  const directory = resolve(root, "drivers", name, "assets");
  const svg = await writeSvg(resolve(directory, "icon.svg"), name, geometry);
  await writeCatalogImages(directory, svg);
}

for (const [filename, geometry] of Object.entries(householdModels)) {
  const target = resolve(root, "drivers", filename);
  await mkdir(resolve(target, ".."), { recursive: true });
  await writeSvg(target, filename.split("/").at(-1), geometry);
}

// The generic driver's neutral icon is retained, as are all imported icons.
{
  const directory = resolve(root, "drivers/openccu-generic/assets");
  await writeCatalogImages(
    directory,
    await readFile(resolve(directory, "icon.svg")),
  );
}

// Existing pairing paths stay stable; family copies receive the same artwork.
const familyCopies = {
  "HmIP-SWDO-2": "HMIP-SWDO/assets/models/swdo-2.svg",
  "HmIP-eTRV-B-2": "HmIP-eTRV-2/assets/models/etrv-b-2.svg",
  "HmIP-eTRV-E": "HmIP-eTRV-2/assets/models/etrv-e.svg",
};
for (const [source, target] of Object.entries(familyCopies)) {
  const destination = resolve(root, "drivers", target);
  await mkdir(resolve(destination, ".."), { recursive: true });
  await copyFile(
    resolve(root, "drivers", source, "assets/icon.svg"),
    destination,
  );
}
